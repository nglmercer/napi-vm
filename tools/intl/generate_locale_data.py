"""Generate ECMA-402 Unicode keyword aliases from CLDR 48 (Unicode license)."""
import hashlib
import json
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

BASE = 'https://raw.githubusercontent.com/unicode-org/cldr/release-48/common/bcp47/'

# Use the release directory listing to cover every keyword, including transform keys.
listing = json.load(urllib.request.urlopen('https://api.github.com/repos/unicode-org/cldr/contents/common/bcp47?ref=release-48'))
rows = {}
hashes = []
for file in sorted(item['name'] for item in listing if item['name'].endswith('.xml')):
    raw = urllib.request.urlopen(BASE + file).read()
    hashes.append((file, hashlib.sha256(raw).hexdigest()))
    tree = ET.fromstring(raw)
    for key in tree.findall('.//key'):
        name = key.attrib['name']
        for typ in key.findall('type'):
            canonical = typ.get('preferred', typ.attrib['name'])
            aliases = typ.get('alias', '').split()
            if 'preferred' in typ.attrib:
                aliases.append(typ.attrib['name'])
            for alias in aliases:
                if alias != canonical and all(3 <= len(s) <= 8 and s.isascii() and s.isalnum() for s in alias.split('-')):
                    rows[(name, alias.lower())] = canonical.lower()
output = '// Generated by tools/intl/generate_locale_data.py from Unicode CLDR release-48.\n// Unicode data license: https://www.unicode.org/license.txt\n'
for file, digest in hashes:
    output += f'// {file}: SHA-256 {digest}\n'
output += 'pub(super) const KEYWORD_ALIASES: &[(&str, &str, &str)] = &[\n'
for (key, alias), canonical in sorted(rows.items()):
    output += f'    ({json.dumps(key)}, {json.dumps(alias)}, {json.dumps(canonical)}),\n'
output += '];\n'
Path('crates/napi-vm-core/src/builtins/intl/data.rs').write_text(output)


url = 'https://raw.githubusercontent.com/unicode-org/cldr/release-48/common/supplemental/supplementalData.xml'
raw = urllib.request.urlopen(url).read()
tree = ET.fromstring(raw)
output += f'// supplementalData.xml SHA-256 {hashlib.sha256(raw).hexdigest()}\n'
def table(name, rows, types):
    global output
    output += f'pub(super) const {name}: &[{types}] = &[\n'
    for row in rows:
        output += '    (' + ', '.join(json.dumps(x) for x in row) + '),\n'
    output += '];\n'
calendars = []
for row in tree.findall('.//calendarPreference'):
    ordering = row.attrib['ordering'].replace('gregorian', 'gregory')
    calendars.extend((region, ordering) for region in row.attrib['territories'].split())
table('CALENDARS', sorted(calendars), '(&str, &str)')
hours = []
for row in tree.findall('.//timeData/hours'):
    preferred = {'h':'h12', 'H':'h23', 'K':'h11', 'k':'h24'}[row.attrib['preferred']]
    hours.extend((region, preferred) for region in row.attrib['regions'].split())
table('HOURS', sorted(hours), '(&str, &str)')
week = {}
for row in tree.findall('.//weekData/*'):
    if row.tag not in ['firstDay','minDays','weekendStart','weekendEnd'] or 'alt' in row.attrib:
        continue
    n = int(row.attrib['count']) if row.tag == 'minDays' else ['mon','tue','wed','thu','fri','sat','sun'].index(row.attrib['day'])+1
    for region in row.attrib['territories'].split():
        week.setdefault(region, {})[row.tag] = n
keys = ['firstDay','minDays','weekendStart','weekendEnd']
default = week['001']
table('WEEK', [(region, *(data.get(key, default[key]) for key in keys)) for region, data in sorted(week.items())], '(&str, u8, u8, u8, u8)')
Path('crates/napi-vm-core/src/builtins/intl/data.rs').write_text(output)
url = 'https://raw.githubusercontent.com/unicode-org/cldr/release-48/common/supplemental/likelySubtags.xml'
raw = urllib.request.urlopen(url).read()
output += f'// likelySubtags.xml SHA-256 {hashlib.sha256(raw).hexdigest()}\n'
likely = [(x.attrib['from'].replace('_', '-'), x.attrib['to'].replace('_', '-')) for x in ET.fromstring(raw).findall('.//likelySubtag')]
table('LIKELY_SUBTAGS', sorted(likely), '(&str, &str)')
Path('crates/napi-vm-core/src/builtins/intl/data.rs').write_text(output)

print(f"Generated {len(rows)} aliases, locale preferences, week data, and {len(likely)} likely-subtag mappings")

url = 'https://raw.githubusercontent.com/unicode-org/cldr-json/48.0.0/cldr-json/cldr-core/availableLocales.json'
raw = urllib.request.urlopen(url).read()
output += f'// availableLocales.json (CLDR JSON 48.0.0) SHA-256 {hashlib.sha256(raw).hexdigest()}\n'
available = set(json.loads(raw)['availableLocales']['full'])
raw = urllib.request.urlopen('https://raw.githubusercontent.com/unicode-org/cldr-json/48.0.0/cldr-json/cldr-core/defaultContent.json').read()
output += f'// defaultContent.json (CLDR JSON 48.0.0) SHA-256 {hashlib.sha256(raw).hexdigest()}\n'
available.update(json.loads(raw)['defaultContent'])
available = sorted(available)
output += 'pub(super) const AVAILABLE_LOCALES: &[&str] = &[\n'
output += ''.join(f'    {json.dumps(locale)},\n' for locale in available)
output += '];\n'
Path('crates/napi-vm-core/src/builtins/intl/data.rs').write_text(output)
